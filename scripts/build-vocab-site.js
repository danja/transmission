/**
 * The two files, as strings.
 *
 * Exported so that the test builds them and compares, rather than asserting
 * that a committed artefact looks plausible. A generated file that is also
 * committed drifts from its source silently, and nothing else would report it.
 */
export async function buildVocabSite () {
  const { sources, turtle } = await mergeSources()

  const parser = new ParserN3({ factory: rdf })
  const dataset = await rdf.dataset().import(parser.import(Readable.from([turtle])))

  const groups = groupTerms(dataset)
  const total = groups.reduce((n, [, terms]) => n + terms.length, 0)

  return { turtle, page: renderPage(groups, total), sources, groups, total, triples: dataset.size }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const built = await buildVocabSite()
  await mkdir(OUT_DIR, { recursive: true })
  await writeFile(join(OUT_DIR, 'transmissions.ttl'), built.turtle)
  await writeFile(join(OUT_DIR, 'index.html'), built.page)

  console.log('deploy/vocab: transmissions.ttl and index.html')
  console.log(`  ${built.sources.length} source file(s): ${built.sources.join(', ')}`)
  for (const [heading, terms] of built.groups) {
    console.log(`  ${String(terms.length).padStart(4)} ${heading.toLowerCase()}`)
  }
  console.log(`  ${built.total} terms, ${built.triples} triples`)
}
