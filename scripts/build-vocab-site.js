// scripts/build-vocab-site.js
//
// Build what http://purl.org/stuff/transmissions/ resolves to.
//
// The PURL redirects to https://hyperdata.it/xmlns/transmissions/, which
// returned 404 because nothing was ever served there. Every trn: IRI published
// by this project, by plugin-universe, by downspout and by JigDAW pointed at
// nothing. This generates the two files that fix it; deploy/nginx/vocab.conf
// serves them.
//
// The terms live in several files under vocabs/ and the namespace is one, so
// the served document is their concatenation. Turtle allows a prefix to be
// declared more than once, none of these files sets @base, and concatenating
// keeps the comments, which are most of the value. The result is parsed before
// it is returned, because a merge that produces something unparseable would
// otherwise be discovered by whoever dereferenced it.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve, join } from 'node:path'
import { Readable } from 'node:stream'
import rdf from 'rdf-ext'
import ParserN3 from '@rdfjs/parser-n3'

const TRN = 'http://purl.org/stuff/transmissions/'
const OWL = 'http://www.w3.org/2002/07/owl#'
const RDFS = 'http://www.w3.org/2000/01/rdf-schema#'
const RDF_TYPE = 'http://www.w3.org/1999/02/22-rdf-syntax-ns#type'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const vocabsDir = join(root, 'vocabs')

export const OUT_DIR = join(root, 'deploy/vocab')

// ontology.ttl first, so the document opens by saying what it is. Anything not
// named here is appended in name order, so adding a vocabulary file needs no
// edit to this list.
const ORDER = ['ontology.ttl', 'profile.ttl', 'project.ttl', 'parameters.ttl', 'formats.ttl', 'actions.ttl', 'djset.ttl']

const escape = s => String(s).replace(/[&<>]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]))

async function mergeSources () {
  const present = (await readdir(vocabsDir)).filter(f => f.endsWith('.ttl'))
  const sources = [
    ...ORDER.filter(f => present.includes(f)),
    ...present.filter(f => !ORDER.includes(f)).sort()
  ]
  if (sources.length === 0) throw new Error('vocabs/ holds no .ttl files, so there is nothing to serve')

  const rule = '# ' + '-'.repeat(76)
  const header = [
    '# http://purl.org/stuff/transmissions/',
    '#',
    '# GENERATED by scripts/build-vocab-site.js from vocabs/. Do not edit: edit the',
    '# file the term lives in and run `npm run build:vocab`.',
    '#',
    '# This is the whole trn: namespace as one document, because the namespace is',
    `# one thing and the sources are ${sources.length}. Sources, in order:`,
    ...sources.map(f => `#   vocabs/${f}`),
    ''
  ].join('\n')

  const parts = [header]
  for (const file of sources) {
    const text = await readFile(join(vocabsDir, file), 'utf8')
    parts.push(`${rule}\n# vocabs/${file}\n${rule}\n\n${text.replace(/\n*$/, '')}\n`)
  }
  return { sources, turtle: parts.join('\n') }
}

/** Group the terms the merged document defines, for the page. */
function groupTerms (dataset) {
  const objectsOf = (subject, predicate) =>
    [...dataset].filter(q => q.subject.value === subject && q.predicate.value === predicate)
      .map(q => q.object.value)

  const subjectsOfType = type => [...new Set(
    [...dataset].filter(q => q.predicate.value === RDF_TYPE && q.object.value === type)
      .map(q => q.subject.value)
  )]

  const describe = iri => ({
    iri,
    name: iri.slice(TRN.length),
    label: objectsOf(iri, `${RDFS}label`)[0] ?? iri.slice(TRN.length),
    comment: objectsOf(iri, `${RDFS}comment`)[0] ?? '',
    parent: objectsOf(iri, `${RDFS}subClassOf`)
      .filter(p => p.startsWith(TRN)).map(p => p.slice(TRN.length))[0] ?? ''
  })

  const own = iris => iris.filter(iri => iri.startsWith(TRN)).map(describe)
    .sort((a, b) => a.name.localeCompare(b.name))

  // Retired terms are listed, because they are in published data and their IRIs
  // have to resolve, but they are kept out of the live groups so that reading
  // the page top to bottom does not offer one as a current term.
  const deprecated = new Set(
    [...dataset].filter(q => q.predicate.value === `${OWL}deprecated` && q.object.value === 'true')
      .map(q => q.subject.value))

  const live = iris => own(iris.filter(iri => !deprecated.has(iri)))

  const classes = new Set(subjectsOfType(`${OWL}Class`))

  // An individual is one of trn:PluginFormat or trn:BusRole as readily as it is
  // an owl:NamedIndividual. Grouping only by the latter filed trn:VST3 under
  // "other", which is where a reader would never look for it.
  const individuals = [...new Set([
    ...subjectsOfType(`${OWL}NamedIndividual`),
    ...[...dataset].filter(q =>
      q.predicate.value === RDF_TYPE && classes.has(q.object.value) && q.subject.value.startsWith(TRN)
    ).map(q => q.subject.value)
  ])].filter(iri => !classes.has(iri))

  const groups = [
    ['Classes', live([...classes])],
    ['Object properties', live(subjectsOfType(`${OWL}ObjectProperty`))],
    ['Datatype properties', live(subjectsOfType(`${OWL}DatatypeProperty`))],
    ['Individuals', live(individuals)]
  ]

  // A term that carries statements but no type at all would otherwise be served
  // in the document and invisible on the page.
  const placed = new Set(groups.flatMap(([, terms]) => terms.map(t => t.iri)))
  const rest = [...new Set([...dataset].map(q => q.subject.value))]
    .filter(iri => iri.startsWith(TRN) && iri !== TRN && !placed.has(iri) && !deprecated.has(iri))
  if (rest.length > 0) groups.push(['Other terms', own(rest)])
  if (deprecated.size > 0) groups.push(['Deprecated', own([...deprecated])])

  return groups
}

const section = (heading, terms) => terms.length === 0 ? '' : `
<h2>${escape(heading)} <span class="count">${terms.length}</span></h2>
<dl>
${terms.map(t => `  <dt id="${escape(t.name)}"><code>trn:${escape(t.name)}</code>${
  t.label !== t.name ? ` <span class="label">${escape(t.label)}</span>` : ''
}${t.parent ? ` <span class="parent">a kind of <a href="#${escape(t.parent)}">trn:${escape(t.parent)}</a></span>` : ''}</dt>
  <dd>${t.comment ? escape(t.comment) : '<span class="undescribed">No description.</span>'}</dd>`).join('\n')}
</dl>`

